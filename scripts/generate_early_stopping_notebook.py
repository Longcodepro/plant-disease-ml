            "class EarlyStopping:\n",
            "    def __init__(self, patience=3, min_delta=0.2, checkpoint_path=None):\n",
            "        self.patience = patience\n",
            "        self.min_delta = min_delta\n",
            "        self.checkpoint_path = checkpoint_path\n",
            "        self.counter = 0\n",
            "        self.best_score = None\n",
            "        self.early_stop = False\n",
            "        self.best_model_weights = None\n",
            "        self.best_epoch = 0\n",
            "\n",
            "    def __call__(self, val_metric, model, epoch):\n",
            "        score = val_metric\n",
            "        if self.best_score is None:\n",
            "            self.best_score = score\n",
            "            self.best_epoch = epoch\n",
            "            self.save_checkpoint(score, model)\n",
            "        elif score < self.best_score + self.min_delta:\n",
            "            self.counter += 1\n",
            "            print(f\"   ⚠️ [EarlyStopping] Không cải thiện đáng kể ({self.counter}/{self.patience} epoch kiên nhẫn).\")\n",
            "            if self.counter >= self.patience:\n",
            "                self.early_stop = True\n",
            "                print(f\"   🛑 [EarlyStopping] ĐẠT ĐỈNH BÃO HÒA! Dừng sớm tại Epoch {epoch}. Kỷ lục tốt nhất ở Epoch {self.best_epoch} ({self.best_score:.2f}%).\")\n",
            "        else:\n",
            "            improvement = score - self.best_score\n",
            "            print(f\"   🌟 [EarlyStopping] KỶ LỤC MỚI: {self.best_score:.2f}% -> {score:.2f}% (+{improvement:.2f}%). Lưu checkpoint!\")\n",
            "            self.best_score = score\n",
            "            self.best_epoch = epoch\n",
            "            self.save_checkpoint(score, model)\n",
            "            self.counter = 0\n",
            "\n",
            "    def save_checkpoint(self, score, model):\n",
            "        self.best_model_weights = copy.deepcopy(model.state_dict())\n",
            "        if self.checkpoint_path:\n",
            "            torch.save({\n",
            "                \"epoch\": self.best_epoch,\n",
            "                \"model_state_dict\": model.state_dict(),\n",
            "                \"best_score\": score\n",
            "            }, self.checkpoint_path)\n",
            "\n",
            "BEST_CKPT_PATH = ROOT_DIR / \"models\" / \"resnet18_long_v2_finetuned_best.pth\"\n",
            "early_stopping = EarlyStopping(patience=3, min_delta=0.2, checkpoint_path=BEST_CKPT_PATH)\n"
